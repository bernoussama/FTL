//! IDNA conversion for pihole-FTL's idn2 command and its callers. to_ascii()
//! is libidn2's idn2_to_ascii_8z() with IDN2_NONTRANSITIONAL (the TR46 mapping,
//! then the IDNA2008 label rules), to_unicode() its idn2_to_unicode_8z8z().
//! Both return libidn2's error codes. Phase 2 module: replaces the libidn2
//! calls in src/args.c, src/api/list.c, src/api/search.c and
//! src/tools/gravity-parseList.c. The rules are in idn/label.rs, the
//! punycode in idn/punycode.rs and the tables in idn/tables.rs (generated by
//! rust/tools/gen_idna2008.py).

mod label;
mod punycode;
mod tables;

use std::ffi::{c_char, c_int, CStr};

use idna_adapter::Adapter;

use crate::buf::FtlRsBuf;

/// Longest label in code points (IDN2_LABEL_MAX_LENGTH)
const LABEL_MAX: usize = 63;
/// Longest domain name without the trailing dot (IDN2_DOMAIN_MAX_LENGTH)
const DOMAIN_MAX: usize = 255;
/// Longest punycode part of an A-label, which is 59 bytes after "xn--"
const PUNYCODE_MAX: usize = LABEL_MAX - 4;
const XN_PREFIX: [u32; 4] = [0x78, 0x6E, 0x2D, 0x2D];

/// The failures of to_ascii() and to_unicode(). The values are libidn2's
/// IDN2_* codes, so C callers see the same numbers.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(i32)]
pub enum IdnError {
    IconvFail = -102,
    EncodingError = -200,
    PunycodeBadInput = -202,
    PunycodeBigOutput = -203,
    PunycodeOverflow = -204,
    TooBigDomain = -205,
    TooBigLabel = -206,
    NotNfc = -300,
    TwoHyphen = -301,
    HyphenStartEnd = -302,
    LeadingCombining = -303,
    Disallowed = -304,
    ContextJ = -305,
    ContextONoRule = -308,
    Unassigned = -309,
    Bidi = -310,
    InvalidNonTransitional = -313,
    AlabelRoundtripFailed = -314,
}

impl IdnError {
    /// The libidn2 code of this error
    pub fn code(self) -> i32 {
        self as i32
    }
}

/// The messages of idn2_strerror() (libidn2 lib/error.c)
