"""Generates rust/src/idn/tables.rs from rust/data (Unicode 15.1.0).

Run from any directory as: python3 -I rust/tools/gen_idna2008.py
"""

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
IDNA2008_FILE = ROOT / "data" / "Idna2008-15.1.0.txt"
MAPPING_FILE = ROOT / "data" / "IdnaMappingTable-15.1.0.txt"
OUT_FILE = ROOT / "src" / "idn" / "tables.rs"

# Statuses of Idna2008-15.1.0.txt that the table keeps. UNASSIGNED is not
# written: a code point in no range is UNASSIGNED (@missing in that file).
IDNA2008_PROPERTIES = {
    "PVALID": "PValid",
    "CONTEXTJ": "ContextJ",
    "CONTEXTO": "ContextO",
    "DISALLOWED": "Disallowed",
}
STD3_STATUSES = {"disallowed_STD3_valid", "disallowed_STD3_mapped"}
# TR46 statuses that libidn2 accepts in non-transitional labels (the STD3 ones
# are accepted separately, with STD3 rules off)
TR46_VALID_STATUSES = {"valid", "deviation"}

LICENSE = """\
// Pi-hole: A black hole for Internet advertisements
// (c) 2026 Pi-hole, LLC (https://pi-hole.net)
// Network-wide ad blocking via your own hardware.
//
// FTL Engine
// Rust static library linked into pihole-FTL
//
// This file is copyright under the latest version of the EUPL.
// Please see LICENSE file for your rights under this license.
"""


def data_rows(path):
    """Yields (first, last, status) for each data line of a Unicode property file."""
    for line in path.read_text(encoding="utf-8").splitlines():
        text = line.split("#", 1)[0].strip()
        if not text:
            continue
        span, status = (field.strip() for field in text.split(";")[:2])
        first, _, last = span.partition("..")
        yield int(first, 16), int(last or first, 16), status


def merged(rows):
    """Sorted (first, last, value) rows, with touching rows of one value joined."""
    result = []
    for first, last, value in sorted(rows):
        if result and result[-1][2] == value and result[-1][1] + 1 == first:
            result[-1] = (result[-1][0], last, value)
        elif result and first <= result[-1][1]:
            raise SystemExit(f"overlapping ranges at U+{first:04X}")
        else:
            result.append((first, last, value))
    return result


def idna2008_ranges():
    rows = []
    for first, last, status in data_rows(IDNA2008_FILE):
        if status == "UNASSIGNED":
            continue
        if status not in IDNA2008_PROPERTIES:
            raise SystemExit(f"unknown IDNA2008 status {status!r}")
        rows.append((first, last, IDNA2008_PROPERTIES[status]))
    return merged(rows)


def std3_ranges():
    rows = [
        (first, last, "STD3")
        for first, last, status in data_rows(MAPPING_FILE)
        if status in STD3_STATUSES
    ]
    return merged(rows)


def tr46_valid_ranges():
    """Code points with TR46 status valid or deviation."""
    return merged(
        (first, last, "TR46")
        for first, last, status in data_rows(MAPPING_FILE)
        if status in TR46_VALID_STATUSES
    )


def tr46_kept_ranges():
    """Code points that TR46 does not give the status disallowed. A code point
    in no range is disallowed, as in libidn2 (not listed in the table)."""
    return merged(
        (first, last, "TR46")
        for first, last, status in data_rows(MAPPING_FILE)
        if status != "disallowed"
    )


def render_pairs(name, doc, ranges):
    lines = [f"/// {line}" for line in doc]
    lines.append(f"pub static {name}: &[(u32, u32)] = &[")
    lines += [f"    (0x{first:04X}, 0x{last:04X})," for first, last, _ in ranges]
    lines += ["];", ""]
    return lines


def render(idna2008, std3, tr46_valid, tr46_kept):
    lines = LICENSE.splitlines() + [
        "",
        "//! Generated by rust/tools/gen_idna2008.py from Unicode 15.1.0 data",
        "//! (see rust/data/README.txt). Do not edit.",
        "",
        "/// IDNA2008 derived property (RFC 5892) of a code point",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum Idna2008 {",
        "    PValid,",
        "    ContextJ,",
        "    ContextO,",
        "    Disallowed,",
        "}",
        "",
        "/// Ranges (first, last, property), sorted. A code point in no range is",
        "/// UNASSIGNED.",
        "pub static IDNA2008: &[(u32, u32, Idna2008)] = &[",
    ]
    lines += [
        f"    (0x{first:04X}, 0x{last:04X}, Idna2008::{prop}),"
        for first, last, prop in idna2008
    ]
    lines += [
        "];",
        "",
        "/// Ranges (first, last), sorted, of the code points that TR46 gives the",
        "/// disallowed_STD3_valid or disallowed_STD3_mapped status.",
        "pub static STD3: &[(u32, u32)] = &[",
    ]
    lines += [f"    (0x{first:04X}, 0x{last:04X})," for first, last, _ in std3]
    lines += ["];", ""]
    lines += render_pairs(
        "TR46_VALID",
        [
            "Ranges (first, last), sorted, of the code points with TR46 status valid",
            "or deviation: the ones libidn2 accepts in a non-transitional label.",
        ],
        tr46_valid,
    )
    lines += render_pairs(
        "TR46_KEPT",
        [
            "Ranges (first, last), sorted, of the code points that TR46 does not",
            "give the status disallowed. A code point in no range is disallowed.",
        ],
        tr46_kept,
    )
    return "\n".join(lines)


def main():
    idna2008 = idna2008_ranges()
    std3 = std3_ranges()
    tr46_valid = tr46_valid_ranges()
    tr46_kept = tr46_kept_ranges()
    OUT_FILE.write_text(
        render(idna2008, std3, tr46_valid, tr46_kept), encoding="utf-8"
    )
    print(
        f"wrote {OUT_FILE}: {len(idna2008)} IDNA2008 ranges, {len(std3)} STD3 ranges, "
        f"{len(tr46_valid)} TR46 valid ranges, {len(tr46_kept)} TR46 kept ranges"
    )


if __name__ == "__main__":
    main()
